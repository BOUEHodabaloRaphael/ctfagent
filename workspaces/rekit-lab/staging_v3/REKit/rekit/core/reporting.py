def _e(x: Any, limit: int = 400) -> str:
    return html.escape(_clean(x, limit), quote=True)


def write_html(report: dict[str, Any], path: str | Path, defang_iocs: bool = True) -> None:
    f = report.get("file", {})
    summ = report.get("summary", {})
    sev = summ.get("findings_by_severity", {})
    mods = report.get("modules", {})
    binary = mods.get("binary")
    out = [f"<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>",
           f"<title>REKit report — {_e(f.get('name', ''))}</title><style>{_HTML_CSS}</style></head><body><main>",
           f"<h1>REKit report <span class='mut'>— {_e(report.get('profile'))} profile</span></h1>",
           "<p class='mut'>Static triage results are indicators, not proof that a file is benign or malicious. Indicators below are defanged.</p>",
           "<div class='card'><table>"]
    rows = [("Target", report.get("target")), ("Type", f"{f.get('type', '')} {('— ' + f['format']) if f.get('format') else ''}"),
            ("Size", f"{f.get('size_bytes', '?')} bytes ({human_size(f.get('size_bytes', 0))})"), ("SHA-256", f.get("sha256")),
            ("MD5", f.get("md5")), ("Entropy", f.get("entropy")), ("Analysed (UTC)", report.get("analyzed_at"))]
    imph = (mods.get("malware") or {}).get("imphash")
    if imph:
        rows.append(("imphash", imph))
    for k, v in rows:
        out.append(f"<tr><th>{_e(k)}</th><td><code>{_e(v, 500)}</code></td></tr>")
    out.append("</table></div><div class='grid'>")
    for name in ("high", "medium", "low", "info"):
        out.append(f"<div class='card'><span class='badge {name}'>{name}</span><br>{sev.get(name, 0)}<span>findings</span></div>")
    out.append("</div>")
    if summ.get("suggested_next_steps"):
        out.append("<h2>Suggested next steps</h2><div class='card'>" + "".join(f"<pre>{_e(s)}</pre>" for s in summ["suggested_next_steps"]) + "</div>")
    if binary:
        out.append(f"<h2>Structure</h2><p>{_e(binary['format'])} {binary['bits']}-bit · {_e(binary['arch'])} · {_e(binary['kind'])} · entry <code>{hex(binary['entry']) if binary.get('entry') else 'n/a'}</code></p>")
        if binary.get("sections"):
            out.append("<table><tr><th>#</th><th>name</th><th>vaddr</th><th>size</th><th>flags</th><th>entropy</th><th></th></tr>")
            for s in binary["sections"][:80]:
                ent = s["entropy"]
                col = "var(--hi)" if (ent or 0) >= 7.2 else ("var(--lo)" if (ent or 0) >= 6 else "var(--ok)")
                bar = f"<div class='bar'><i style='width:{min(100, (ent or 0) / 8 * 100):.0f}%;background:{col}'></i></div>" if ent is not None else ""
                out.append(f"<tr><td>{s['index']}</td><td><code>{_e(s['name'], 60)}</code></td><td><code>0x{s['vaddr']:x}</code></td><td>{s['size']}</td><td><code>{_e(s['flags'])}</code></td><td>{'' if ent is None else ent}</td><td>{bar}</td></tr>")
            out.append("</table>")
        prot = binary.get("protections") or {}
        if prot:
            out.append("<h3>Protections</h3><div class='card'><table>" + "".join(f"<tr><th>{_e(k)}</th><td>{_e(v)}</td></tr>" for k, v in prot.items()) + "</table></div>")
        if binary.get("imports"):
            groups: dict[str, list[str]] = {}
            for imp in binary["imports"]:
                groups.setdefault(imp.get("lib") or "(symbols)", []).append(imp.get("name") or f"#{imp.get('ordinal')}")
            out.append(f"<h3>Imports ({len(binary['imports'])})</h3>")
            for lib, names in sorted(groups.items()):
                out.append(f"<details><summary><code>{_e(lib, 80)}</code> <span class='mut'>({len(names)})</span></summary><pre>{_e(', '.join(names), 4000)}</pre></details>")
    out.append("<h2>Findings</h2>")
    findings = sorted(report.get("findings", []), key=lambda x: -SEV_ORDER.get(x.get("severity", "info"), 0))
    if not findings:
        out.append("<p>No findings were generated by the selected modules.</p>")
    for it in findings:
        s = it.get("severity", "info")
        out.append(f"<div class='card'><span class='badge {_e(s)}'>{_e(s.upper())}</span> <strong>{_e(it.get('title'), 200)}</strong> "
                   f"<span class='mut'>{_e(it.get('id'))} · confidence {_e(it.get('confidence'))}"
                   + (f" · ATT&amp;CK {_e(', '.join(it['attack']))}" if it.get("attack") else "") + "</span>"
                   f"<p>{_e(it.get('description'), 900)}</p>")
        if it.get("evidence"):
            out.append("<details open><summary>Evidence</summary><pre>" + "\n".join(_e(_maybe_defang(e, defang_iocs), 400) for e in it["evidence"][:40]) + "</pre></details>")
        if it.get("next_steps"):
            out.append("<details><summary>Next steps</summary><pre>" + "\n".join(_e(x) for x in it["next_steps"]) + "</pre></details>")
        if it.get("limitations"):
            out.append("<p class='mut'>Limitations: " + _e(" ".join(it["limitations"]), 800) + "</p>")
        out.append("</div>")
    if report.get("errors"):
        out.append("<h2>Errors</h2><pre>" + "\n".join(_e(e) for e in report["errors"]) + "</pre>")
    out.append("<h2>Analysis limitations</h2><ul>" + "".join(f"<li>{_e(x, 500)}</li>" for x in report.get("limitations", [])) + "</ul>")
    t = mods.get("timings_ms")
    if t:
        out.append("<p class='mut'>Timings (ms): " + _e(", ".join(f"{k}={v}" for k, v in t.items())) + f" · REKit {_e(report.get('version'))}</p>")
    out.append("</main></body></html>")
    _prep(path).write_text("\n".join(out), encoding="utf-8")


def _color(enabled: bool):
    codes = {"high": "91", "medium": "93", "low": "33", "info": "96", "bold": "1", "dim": "90", "ok": "92"}

    def paint(text: str, kind: str) -> str:
        return f"\033[{codes[kind]}m{text}\033[0m" if enabled else text
    return paint


def print_console(report: dict[str, Any], stream=None, verbose: bool = False, defang_iocs: bool = True) -> None:
    stream = stream or sys.stdout
    use_color = hasattr(stream, "isatty") and stream.isatty() and "NO_COLOR" not in os.environ
    c = _color(use_color)
    f = report.get("file", {})

    def out(s: str = ""):
        print(s, file=stream)
    out(c(f"REKit {report['version']} · profile={report['profile']}", "bold"))
    out(f"Target : {_clean(report['target'])}")
    out(f"Type   : {f.get('type')}" + (f" — {_clean(f['format'])}" if f.get("format") else ""))
    out(f"Size   : {f.get('size_bytes')} bytes   Entropy: {f.get('entropy')}")
    out(f"SHA-256: {f.get('sha256')}")
    binary = report.get("modules", {}).get("binary")
    if binary:
        out(f"Entry  : {hex(binary['entry']) if binary.get('entry') else 'n/a'}   Sections: {len(binary.get('sections', []))}   Imports: {len(binary.get('imports', []))}")
        prot = binary.get("protections", {})
        if binary["format"] == "ELF":
            out("Protect: " + "  ".join(f"{k.upper()}={prot.get(k, '?')}" for k in ("nx", "pie", "relro", "canary", "fortify")))
        if verbose and binary.get("sections"):
            out(c("Sections:", "bold"))
            for s in binary["sections"]:
                out(f"  {s['index']:>2} {_clean(s['name'], 24):<24} va=0x{s['vaddr']:<10x} size={s['size']:<9} {s['flags']}  H={'' if s['entropy'] is None else s['entropy']:.3}" if s["entropy"] is not None else f"  {s['index']:>2} {_clean(s['name'], 24):<24} va=0x{s['vaddr']:<10x} size={s['size']:<9} {s['flags']}")
    summ = report.get("summary", {})
    sev = summ.get("findings_by_severity", {})
    out(f"Findings: " + "  ".join(c(f"{k}={sev.get(k, 0)}", k) for k in ("high", "medium", "low", "info")))
    out()
    for it in sorted(report["findings"], key=lambda x: -SEV_ORDER.get(x["severity"], 0)):
        out(f"[{c(it['severity'].upper(), it['severity'])}] {_clean(it['title'], 120)} {c('(' + it['id'] + ', confidence=' + str(it['confidence']) + ')', 'dim')}")
        limit = 12 if verbose else 3
        for e in it.get("evidence", [])[:limit]:
            out(f"      {_clean(_maybe_defang(e, defang_iocs), 160)}")
        if len(it.get("evidence", [])) > limit:
            out(c(f"      … {len(it['evidence']) - limit} more (use --verbose or a report file)", "dim"))
        for n in it.get("next_steps", [])[:2]:
            out(c(f"      → {n}", "ok"))
    if summ.get("suggested_next_steps"):
        out()
        out(c("Suggested next steps:", "bold"))
        for s in summ["suggested_next_steps"][:5]:
            out(f"  {s}")
    for err in report.get("errors", []):
        out(c(f"[ERROR] {_clean(err)}", "high"))
    for lim in report.get("limitations", []):
        out(c(f"[LIMITATION] {lim}", "dim"))
