from typing import Any

from .util import defang, human_size

_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")
SEV_ORDER = {"high": 3, "medium": 2, "low": 1, "info": 0}


def _prep(path: str | Path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    return p


def write_json(report: dict[str, Any], path: str | Path) -> None:
    _prep(path).write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str) + "\n", encoding="utf-8")


def _clean(text: Any, limit: int = 300) -> str:
    s = _CTRL.sub("\ufffd", str(text))
    return s if len(s) <= limit else s[:limit] + "…"


def _md_code(text: Any, limit: int = 300) -> str:
    s = _clean(text, limit).replace("`", "'").replace("\n", " ")
    return f"`{s}`"


_DEFANGABLE = re.compile(r"^(?:(?:https?|ftp)://\S+|\d{1,3}(?:\.\d{1,3}){3}|[\w.+-]+@[\w.-]+\.[a-z]{2,}|(?:[a-z0-9-]+\.)+(?:com|net|org|info|biz|io|co|ru|cn|xyz|top|club|online|site|tk|cc|su|pw|onion|me|ws|tv|us|uk|de|fr))$", re.I)


def _maybe_defang(value: str, on: bool) -> str:
    return defang(value) if on and _DEFANGABLE.search(value) else value


def write_markdown(report: dict[str, Any], path: str | Path, defang_iocs: bool = True) -> None:
    f = report.get("file", {})
    lines = [f"# REKit report — {report.get('profile', 'unknown')}", "",
             f"- **Target:** {_md_code(report.get('target', ''))}", f"- **Date UTC:** {report.get('analyzed_at', '')}",
             f"- **Type:** {f.get('type', 'unknown')}" + (f" — {_clean(f['format'])}" if f.get("format") else ""),
             f"- **Size:** {f.get('size_bytes', '?')} bytes", f"- **SHA-256:** `{f.get('sha256', '')}`",
             f"- **MD5:** `{f.get('md5', '')}`", f"- **Entropy:** {f.get('entropy', '?')}"]
    imph = (report.get("modules", {}).get("malware") or {}).get("imphash")
    if imph:
        lines.append(f"- **imphash:** `{imph}`")
    lines += ["", "> Static triage results are indicators, not proof that a file is benign or malicious.", ""]
    summ = report.get("summary", {})
    if summ:
        sev = summ.get("findings_by_severity", {})
        lines += ["## Summary", "", "| high | medium | low | info |", "|---|---|---|---|",
                  f"| {sev.get('high', 0)} | {sev.get('medium', 0)} | {sev.get('low', 0)} | {sev.get('info', 0)} |", ""]
        if summ.get("suggested_next_steps"):
            lines += ["**Suggested next steps**", ""] + [f"- {_md_code(s)}" for s in summ["suggested_next_steps"]] + [""]
    binary = report.get("modules", {}).get("binary")
    if binary:
        lines += ["## Structure", "", f"{binary['format']} {binary['bits']}-bit, {binary['arch']}, {binary['kind']}; entry `{hex(binary['entry']) if binary.get('entry') else 'n/a'}`", ""]
        if binary.get("sections"):
            lines += ["| # | name | vaddr | size | flags | entropy |", "|---|---|---|---|---|---|"]
            for s in binary["sections"][:60]:
                lines.append(f"| {s['index']} | {_md_code(s['name'], 40)} | `0x{s['vaddr']:x}` | {s['size']} | {s['flags']} | {s['entropy'] if s['entropy'] is not None else ''} |")
            lines.append("")
    lines += ["## Findings", ""]
    findings = sorted(report.get("findings", []), key=lambda x: -SEV_ORDER.get(x.get("severity", "info"), 0))
    if not findings:
        lines.append("No findings were generated by the selected modules.")
    for item in findings:
        lines += [f"### [{item.get('severity', 'info').upper()}] {_clean(item.get('title', 'Finding'), 160)}", "", _clean(item.get("description", ""), 800), "",
                  f"- ID: `{item.get('id', '')}` — Confidence: **{item.get('confidence', 'unknown')}**" + (f" — ATT&CK hints: {', '.join(item['attack'])}" if item.get("attack") else "")]
        if item.get("evidence"):
            lines += ["- Evidence:"] + [f"  - {_md_code(_maybe_defang(e, defang_iocs))}" for e in item["evidence"][:40]]
        if item.get("next_steps"):
            lines += ["- Next steps:"] + [f"  - {_md_code(e)}" for e in item["next_steps"]]
        if item.get("limitations"):
            lines += ["- Limitations:"] + [f"  - {_clean(e, 300)}" for e in item["limitations"]]
        lines.append("")
    if report.get("errors"):
        lines += ["## Errors", ""] + [f"- {_clean(e)}" for e in report["errors"]] + [""]
    if report.get("limitations"):
        lines += ["## Analysis limitations", ""] + [f"- {e}" for e in report["limitations"]] + [""]
    _prep(path).write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


